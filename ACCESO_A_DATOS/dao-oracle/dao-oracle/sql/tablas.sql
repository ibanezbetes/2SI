PROMPT ====== CREACIÓN DE TABLAS (PADRES) ======
CREATE TABLE ARTICULO (
    ID_ARTICULO     NUMBER,
    NOMBRE          VARCHAR2(120),
    DETALLE         VARCHAR2(255),
    COD_REFERENCIA  VARCHAR2(24),
    CANTIDAD_DISP   NUMBER,
    PRECIO_UNIT     NUMBER(8,2),
    CONSTRAINT PK_ARTICULO PRIMARY KEY (ID_ARTICULO),
    CONSTRAINT CK_ARTICULO_NOMBRE_NN CHECK (NOMBRE IS NOT NULL),
    CONSTRAINT CK_ARTICULO_REF_NN   CHECK (COD_REFERENCIA IS NOT NULL),
    CONSTRAINT CK_ARTICULO_CANT_OK  CHECK (CANTIDAD_DISP IS NOT NULL AND CANTIDAD_DISP >= 0),
    CONSTRAINT CK_ARTICULO_PREC_OK  CHECK (PRECIO_UNIT IS NOT NULL AND PRECIO_UNIT > 0),
    CONSTRAINT UQ_ARTICULO_REF      UNIQUE (COD_REFERENCIA)
);

CREATE TABLE PROVEEDOR_SOCIEDAD (
    ID_PROV_SOC     NUMBER,
    CIF             VARCHAR2(9),
    CP              NUMBER(5),
    SITIO_WEB       VARCHAR2(120),
    RAZON_SOCIAL    VARCHAR2(120),
    TELEFONO        NUMBER(9),
    DIRECCION       VARCHAR2(160),
    PERSONA_CONTACTO VARCHAR2(60),
    LOCALIDAD       VARCHAR2(60),
    CONSTRAINT PK_PROV_SOC PRIMARY KEY (ID_PROV_SOC),
    CONSTRAINT UQ_PROV_SOC_CIF UNIQUE (CIF),
    CONSTRAINT CK_PROV_SOC_REQ CHECK (
        CIF IS NOT NULL AND CP IS NOT NULL AND RAZON_SOCIAL IS NOT NULL AND
        TELEFONO IS NOT NULL AND DIRECCION IS NOT NULL AND LOCALIDAD IS NOT NULL
    ),
    CONSTRAINT CK_PROV_SOC_TEL CHECK (TELEFONO BETWEEN 600000000 AND 999999999)
);

CREATE TABLE PROVEEDOR_AUTONOMO (
    ID_PROV_AUT     NUMBER,
    MARCA_COMERCIAL VARCHAR2(120),
    DNI             VARCHAR2(9),
    TELEFONO        NUMBER(9),
    LOCALIDAD       VARCHAR2(60),
    DIRECCION       VARCHAR2(160),
    NOMBRE          VARCHAR2(60),
    APELLIDOS       VARCHAR2(120),
    CONSTRAINT PK_PROV_AUT PRIMARY KEY (ID_PROV_AUT),
    CONSTRAINT UQ_PROV_AUT_DNI UNIQUE (DNI),
    CONSTRAINT CK_PROV_AUT_REQ CHECK (
        DNI IS NOT NULL AND TELEFONO IS NOT NULL AND LOCALIDAD IS NOT NULL AND
        DIRECCION IS NOT NULL AND NOMBRE IS NOT NULL AND APELLIDOS IS NOT NULL
    ),
    CONSTRAINT CK_PROV_AUT_TEL CHECK (TELEFONO BETWEEN 600000000 AND 999999999)
);

CREATE TABLE USUARIO_TIENDA (
    ID_USUARIO  NUMBER,
    ALIAS       VARCHAR2(60),
    TELEFONO    NUMBER(9),
    HASH_CLAVE  VARCHAR2(255),
    CORREO      VARCHAR2(120),
    NOMBRE      VARCHAR2(60),
    APELLIDO    VARCHAR2(120),
    CONSTRAINT PK_USUARIO_TIENDA PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_ALIAS  UNIQUE (ALIAS),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_REQ CHECK (
        ALIAS IS NOT NULL AND TELEFONO IS NOT NULL AND HASH_CLAVE IS NOT NULL AND
        CORREO IS NOT NULL AND NOMBRE IS NOT NULL AND APELLIDO IS NOT NULL
    ),
    CONSTRAINT CK_USUARIO_TEL CHECK (TELEFONO BETWEEN 600000000 AND 999999999)
);

CREATE TABLE CLIENTE_PARTICULAR (
    ID_CLIENTE NUMBER,
    CONSTRAINT PK_CLIENTE_PARTICULAR PRIMARY KEY (ID_CLIENTE)
);

CREATE TABLE FACTURA_COMPRA (
    ID_FACT_COMP NUMBER,
    FECHA        DATE DEFAULT SYSDATE,
    CONSTRAINT PK_FACTURA_COMPRA PRIMARY KEY (ID_FACT_COMP),
