PROMPT ====== CREACIÓN DE TABLAS (DEPENDIENTES) ======
CREATE TABLE PEDIDO_PROVEEDOR (
    ID_PED_PROV NUMBER,
    FECHA       DATE DEFAULT SYSDATE,
    ID_PROV_SOC NUMBER,
    CONSTRAINT PK_PEDIDO_PROVEEDOR PRIMARY KEY (ID_PED_PROV),
    CONSTRAINT CK_PED_PROV_REQ CHECK (FECHA IS NOT NULL AND ID_PROV_SOC IS NOT NULL),
    CONSTRAINT FK_PED_PROV_SOC FOREIGN KEY (ID_PROV_SOC) REFERENCES PROVEEDOR_SOCIEDAD(ID_PROV_SOC)
);

CREATE TABLE RECEPCION_PEDIDO (
    ID_RECEPCION NUMBER,
    ACEPTADO     VARCHAR2(2),
    FECHA        DATE DEFAULT SYSDATE,
    ID_PED_PROV  NUMBER,
    ID_FACT_COMP NUMBER,
    CONSTRAINT PK_RECEPCION_PEDIDO PRIMARY KEY (ID_RECEPCION),
    CONSTRAINT CK_RECEP_REQ CHECK (ACEPTADO IS NOT NULL AND FECHA IS NOT NULL AND ID_PED_PROV IS NOT NULL AND ID_FACT_COMP IS NOT NULL),
    CONSTRAINT CK_RECEP_ACEPTADO CHECK (ACEPTADO IN ('SI','NO')),
    CONSTRAINT FK_RECEP_PED  FOREIGN KEY (ID_PED_PROV)  REFERENCES PEDIDO_PROVEEDOR(ID_PED_PROV),
    CONSTRAINT FK_RECEP_FACT FOREIGN KEY (ID_FACT_COMP) REFERENCES FACTURA_COMPRA(ID_FACT_COMP)
);

CREATE TABLE ALBARAN_AUTONOMO (
    ID_ALBARAN  NUMBER,
    FECHA       DATE DEFAULT SYSDATE,
    ID_PROV_AUT NUMBER,
    CONSTRAINT PK_ALBARAN_AUTONOMO PRIMARY KEY (ID_ALBARAN),
    CONSTRAINT CK_ALBARAN_REQ CHECK (FECHA IS NOT NULL AND ID_PROV_AUT IS NOT NULL),
    CONSTRAINT FK_ALB_AUT FOREIGN KEY (ID_PROV_AUT) REFERENCES PROVEEDOR_AUTONOMO(ID_PROV_AUT)
);

CREATE TABLE TICKET_CAJA (
    ID_TICKET     NUMBER,
    FECHA         DATE DEFAULT SYSDATE,
    FORMA_PAGO    VARCHAR2(20),
    NUM_OPERACION VARCHAR2(60),
    ID_CLIENTE    NUMBER,
    CONSTRAINT PK_TICKET_CAJA PRIMARY KEY (ID_TICKET),
    CONSTRAINT CK_TICKET_REQ CHECK (FECHA IS NOT NULL AND FORMA_PAGO IS NOT NULL AND ID_CLIENTE IS NOT NULL),
    CONSTRAINT CK_TICKET_PAGO CHECK (FORMA_PAGO IN ('EFECTIVO','TARJETA','BIZUM','OTRO')),
    CONSTRAINT FK_TICKET_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE_PARTICULAR(ID_CLIENTE)
);

CREATE TABLE DEVOLUCION_TICKET (
    ID_DEV        NUMBER,
    FECHA         DATE DEFAULT SYSDATE,
    MOTIVO        VARCHAR2(255),
    TIPO_REEMBOLSO VARCHAR2(20),
    UNIDADES      NUMBER,
    ID_TICKET     NUMBER,
    CONSTRAINT PK_DEVOLUCION_TICKET PRIMARY KEY (ID_DEV),
    CONSTRAINT CK_DEV_TICKET_REQ CHECK (FECHA IS NOT NULL AND MOTIVO IS NOT NULL AND TIPO_REEMBOLSO IS NOT NULL AND UNIDADES IS NOT NULL AND ID_TICKET IS NOT NULL),
    CONSTRAINT CK_DEV_TIPO CHECK (TIPO_REEMBOLSO IN ('EFECTIVO','TARJETA','BIZUM','OTRO')),
    CONSTRAINT CK_DEV_UNIDADES CHECK (UNIDADES > 0),
    CONSTRAINT FK_DEV_TICKET FOREIGN KEY (ID_TICKET) REFERENCES TICKET_CAJA(ID_TICKET)
);

CREATE TABLE DIRECCION_ENVIO (
    ID_DIRECCION NUMBER,
    CP           NUMBER(5),
    CALLE        VARCHAR2(160),
    PROVINCIA    VARCHAR2(60),
    LOCALIDAD    VARCHAR2(60),
    PRINCIPAL    VARCHAR2(2),
    ID_USUARIO   NUMBER,
    CONSTRAINT PK_DIRECCION_ENVIO PRIMARY KEY (ID_DIRECCION),
    CONSTRAINT CK_DIR_ENV_REQ CHECK (CP IS NOT NULL AND CALLE IS NOT NULL AND PROVINCIA IS NOT NULL AND LOCALIDAD IS NOT NULL AND PRINCIPAL IS NOT NULL AND ID_USUARIO IS NOT NULL),
    CONSTRAINT CK_DIR_ENV_PRINC CHECK (PRINCIPAL IN ('SI','NO')),
    CONSTRAINT FK_DIR_ENV_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_TIENDA(ID_USUARIO)
);

CREATE TABLE DATOS_FACTURACION (
    ID_DATO_FACT NUMBER,
    EMPRESA      VARCHAR2(120),
    CIF          VARCHAR2(9),
    DIRECCION    VARCHAR2(160),
    ID_USUARIO   NUMBER,
    CONSTRAINT PK_DATOS_FACTURACION PRIMARY KEY (ID_DATO_FACT),
    CONSTRAINT CK_DATO_FACT_REQ CHECK (EMPRESA IS NOT NULL AND CIF IS NOT NULL AND DIRECCION IS NOT NULL AND ID_USUARIO IS NOT NULL),
    CONSTRAINT FK_DATO_FACT_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_TIENDA(ID_USUARIO)
);

CREATE TABLE FACTURA_ONLINE (
    ID_FACT_ONLINE NUMBER,
    FECHA          DATE DEFAULT SYSDATE,
    METODO_PAGO    VARCHAR2(20),
    COSTE_ENVIO    NUMBER(6,2),
    ID_USUARIO     NUMBER,
    CONSTRAINT PK_FACTURA_ONLINE PRIMARY KEY (ID_FACT_ONLINE),
    CONSTRAINT CK_FACT_ON_REQ CHECK (FECHA IS NOT NULL AND METODO_PAGO IS NOT NULL AND COSTE_ENVIO IS NOT NULL AND ID_USUARIO IS NOT NULL),
    CONSTRAINT CK_FACT_ON_PAGO CHECK (METODO_PAGO IN ('TARJETA','PAYPAL','BIZUM','TRANSFERENCIA')),
    CONSTRAINT CK_FACT_ON_ENVIO CHECK (COSTE_ENVIO >= 0),
    CONSTRAINT FK_FACT_ON_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_TIENDA(ID_USUARIO)
);

CREATE TABLE ENVIO_ONLINE (
    ID_ENVIO        NUMBER,
    FECHA           DATE DEFAULT SYSDATE,
    COD_SEGUIMIENTO VARCHAR2(60),
    TRANSPORTISTA   VARCHAR2(120),
    ID_FACT_ONLINE  NUMBER,
    CONSTRAINT PK_ENVIO_ONLINE PRIMARY KEY (ID_ENVIO),
    CONSTRAINT CK_ENV_ON_REQ CHECK (FECHA IS NOT NULL AND COD_SEGUIMIENTO IS NOT NULL AND TRANSPORTISTA IS NOT NULL AND ID_FACT_ONLINE IS NOT NULL),
    CONSTRAINT FK_ENV_ON_FACT FOREIGN KEY (ID_FACT_ONLINE) REFERENCES FACTURA_ONLINE(ID_FACT_ONLINE)
);

CREATE TABLE DETALLE_FACTURA_ONLINE (
    ID_DETALLE     NUMBER,
    CANTIDAD       NUMBER,
    IMPORTE        NUMBER(8,2),
    ID_FACT_ONLINE NUMBER,
    ID_ARTICULO    NUMBER,
    CONSTRAINT PK_DETALLE_FACTURA_ONLINE PRIMARY KEY (ID_DETALLE),
    CONSTRAINT CK_DFO_REQ     CHECK (CANTIDAD IS NOT NULL AND IMPORTE IS NOT NULL AND ID_FACT_ONLINE IS NOT NULL AND ID_ARTICULO IS NOT NULL),
    CONSTRAINT CK_DFO_CANT    CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DFO_IMPORTE CHECK (IMPORTE > 0),
    CONSTRAINT FK_DFO_FACT FOREIGN KEY (ID_FACT_ONLINE) REFERENCES FACTURA_ONLINE(ID_FACT_ONLINE),
    CONSTRAINT FK_DFO_ART  FOREIGN KEY (ID_ARTICULO)    REFERENCES ARTICULO(ID_ARTICULO)
);

CREATE TABLE DETALLE_TICKET (
    ID_DET_TICKET NUMBER,
    IMPORTE       NUMBER(8,2),
    CANTIDAD      NUMBER,
    ID_TICKET     NUMBER,
    ID_ARTICULO   NUMBER,
    CONSTRAINT PK_DETALLE_TICKET PRIMARY KEY (ID_DET_TICKET),
    CONSTRAINT CK_DT_REQ      CHECK (IMPORTE IS NOT NULL AND CANTIDAD IS NOT NULL AND ID_TICKET IS NOT NULL AND ID_ARTICULO IS NOT NULL),
    CONSTRAINT CK_DT_IMPORTE  CHECK (IMPORTE > 0),
    CONSTRAINT CK_DT_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT FK_DT_TICKET FOREIGN KEY (ID_TICKET)  REFERENCES TICKET_CAJA(ID_TICKET),
    CONSTRAINT FK_DT_ART    FOREIGN KEY (ID_ARTICULO) REFERENCES ARTICULO(ID_ARTICULO)
);

CREATE TABLE DETALLE_PEDIDO_PROV (
    ID_DET_PED  NUMBER,
    IMPORTE     NUMBER(8,2),
    CANTIDAD    NUMBER,
    ID_ARTICULO NUMBER,
    ID_PED_PROV NUMBER,
    CONSTRAINT PK_DETALLE_PEDIDO_PROV PRIMARY KEY (ID_DET_PED),
    CONSTRAINT CK_DPP_REQ     CHECK (IMPORTE IS NOT NULL AND CANTIDAD IS NOT NULL AND ID_ARTICULO IS NOT NULL AND ID_PED_PROV IS NOT NULL),
    CONSTRAINT CK_DPP_IMPORTE CHECK (IMPORTE > 0),
    CONSTRAINT CK_DPP_CANT    CHECK (CANTIDAD > 0),
    CONSTRAINT FK_DPP_ART FOREIGN KEY (ID_ARTICULO)  REFERENCES ARTICULO(ID_ARTICULO),
    CONSTRAINT FK_DPP_PED FOREIGN KEY (ID_PED_PROV)  REFERENCES PEDIDO_PROVEEDOR(ID_PED_PROV)
);

